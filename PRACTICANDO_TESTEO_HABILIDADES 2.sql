--CASE WITH JOIN
SELECT NOMBRE, APELLIDO, AFP, ISR,	
CASE
	WHEN APELLIDO = 'Lopoldo' THEN 'EL ABUSADOR'
	WHEN APELLIDO = 'Diaz' AND AFP = 789.25 THEN 'EL AMANECER'
	ELSE APODO
END AS RESULTADO

FROM EMPLEADOS E
JOIN NOMINA N ON CODIGO_EMPLEADO = CODIGO

--CASE WITH JOIN-2--
SELECT NOMBRE, APELLIDO, DEPARTAMENTO, BONOS, SUBSIDIO,
	CASE 
		WHEN NOMBRE = 'JUAN SORILLA' AND APELLIDO = 'Lopoldo' THEN 'EL MEJOR'
		WHEN NOMBRE = 'JUAN LA LUZ'  AND APELLIDO = 'PEREZ' THEN 'EL CATA'
		WHEN BONOS = 800 AND SUBSIDIO = 100 THEN 'BUEN EMPLEADO'
		WHEN BONOS = 900 AND SUBSIDIO = 125 THEN 'GRAN GERENTE'
ELSE 'NO HAY EMPLEADOS' 
	END AS COMBINACION
FROM EMPLEADOS E
JOIN NOMINA N ON CODIGO_EMPLEADO = CODIGO 
ORDER BY APELLIDO ASC;


