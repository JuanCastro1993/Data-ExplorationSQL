--JOIN
SELECT E.CODIGO_EMPLEADO, E.APELLIDO,SUELDO, N.SUBSIDIO
FROM EMPLEADOS E
JOIN NOMINA N ON E.CODIGO_EMPLEADO = N.CODIGO
WHERE SUBSIDIO <= 148;

--CLAUSULA GROUP BY
SELECT NOMBRE, APELLIDO, APODO, MAX(BONOS) AS MAX_BONOS
FROM EMPLEADOS E
JOIN NOMINA N ON E.CODIGO_EMPLEADO = N.CODIGO
GROUP BY NOMBRE, APELLIDO, APODO
HAVING MAX(BONOS) >=100;

DELETE FROM EMPLEADOS
WHERE CODIGO_EMPLEADO = 1030;


--CLAUSULA WHERE
SELECT NOMBRE, SUELDO, DEPARTAMENTO
FROM EMPLEADOS
WHERE NOMBRE != 'JUAN SORRILLA';

SELECT NOMBRE, APELLIDO, SUELDO, AVG(BONOS) AS AVG_BONOS
FROM EMPLEADOS E
JOIN NOMINA N ON E.	CODIGO_EMPLEADO = N. CODIGO
WHERE APELLIDO = 'Lopoldo'
GROUP BY NOMBRE, APELLIDO, SUELDO
HAVING AVG(BONOS) > 25;

--CLAUSULA HAVING
SELECT NOMBRE, APELLIDO, AVG(SUELDO) AS AVG_SUELDO, MAX(AFP) AS MAX_AFP
FROM EMPLEADOS E
JOIN NOMINA N ON E.CODIGO_EMPLEADO = N.CODIGO
GROUP BY NOMBRE, APELLIDO
HAVING AVG(SUELDO)> =75000 AND MAX(AFP)>=741.25;

SELECT APELLIDO, SUELDO, COUNT(SUELDO) AS CONTEO_DE_SUELDO
FROM EMPLEADOS E
JOIN NOMINA N ON E.CODIGO_EMPLEADO = N.CODIGO
GROUP BY APELLIDO, SUELDO
HAVING COUNT(SUELDO) > 1;


