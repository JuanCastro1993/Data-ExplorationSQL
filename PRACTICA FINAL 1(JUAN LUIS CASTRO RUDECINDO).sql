);


CREATE TRIGGER TRI_CREACION
ON CLIENTES
AFTER INSERT
AS 
	BEGIN
	DECLARE @NOMBRE_USUARIO VARCHAR(25);
	SET @NOMBRE_USUARIO = SUSER_NAME();
	INSERT INTO CONTROL VALUES (@NOMBRE_USUARIO,'CREAR_CLIENTE',GETDATE())
	END;

