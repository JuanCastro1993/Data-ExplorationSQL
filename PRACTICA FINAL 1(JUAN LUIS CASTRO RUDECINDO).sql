---PELICULAS DISPONIBLES---------------------------------------------------------------------------------
SELECT P.ID_PELICULA, NOMBRE_PELICULA, SALA, (CAPACIDAD_PERSONAS-ENTRADAS_VENDIDAS) AS 'ASIENTOS_DISPONIBLES EN SALA',
CASE 
	WHEN ENTRADAS_VENDIDAS <200 THEN 'PELICULA DISPONIBLE'
	WHEN ENTRADAS_VENDIDAS <75 THEN 'PELICULA DISPONIBLE'
	WHEN ENTRADAS_VENDIDAS <100 THEN 'PELICULA DISPONIBLE'
	WHEN ENTRADAS_VENDIDAS <100 THEN 'PELICULA DISPONIBLE'
	WHEN ENTRADAS_VENDIDAS <75 THEN 'PELICULA DISPONIBLE'
ELSE 'LA PELICULA NO ESTA DISPONIBLE'
END AS DISPONIBILIDAD
FROM PELICULAS P
JOIN ALQUILER A ON P.ID_PELICULA = A.ID_PELICULA


---PELICULAS ALQUILADAS
SELECT P.ID_PELICULA,P.ID_CLIENTE,NOMBRE_PELICULA,SALA
FROM PELICULAS P
JOIN ALQUILER A ON P.ID_PELICULA = A.ID_PELICULA
ORDER BY SALA

---PELICULAS CON UN DETERMINADO CLIENTE EN MOMENTO ACTUAL
SELECT C.NOMBRE, P.NOMBRE_PELICULA
FROM CLIENTES C
JOIN PELICULAS P ON C.ID_CLIENTE = P.ID_CLIENTE

---EMPLEADOS ACTIVOS
