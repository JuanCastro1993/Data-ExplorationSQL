CREATE DATABASE CINEMAJUAN
USE CINEMAJUAN


CREATE TABLE CLIENTES(
ID_CLIENTE INT IDENTITY (100,2),
NOMBRE VARCHAR (25) NOT NULL,
APELLIDO VARCHAR (25) NOT NULL,
EMAIL VARCHAR (20),
TELEFONO VARCHAR (20),
TIPO_CLIENTE VARCHAR(25) NOT NULL,
ESTATUS BIT,
FECHA DATE
CONSTRAINT PK_ID_CLIENTE PRIMARY KEY (ID_CLIENTE)
);

CREATE TABLE PELICULAS(
ID_PELICULA INT IDENTITY (01,1),
ID_CLIENTE INT FOREIGN KEY REFERENCES CLIENTES(ID_CLIENTE),
NOMBRE_PELICULA VARCHAR (25),
ANO_FILMACION VARCHAR(5),
STOCK_PELICULAS INT,
CATEGORIA_PELICULA VARCHAR (25),
);

CREATE TABLE ALQUILER (
ID_CLIENTE INT FOREIGN KEY REFERENCES CLIENTES(ID_CLIENTE),
ID_PELICULA INT,
SALA VARCHAR(10),
ENTRADAS_VENDIDAS INT,
CAPACIDAD_PERSONAS INT,
HORA_FUNCION TIME
);



CREATE TABLE EMPLEADO(
NOMBRE_EMPLEADO VARCHAR (25),
APELLIDO VARCHAR (25),
ID_EMPLEADO INT IDENTITY(13,3),
PUESTO VARCHAR(25),
ESTATUS BIT
);

