--6.CASE
SELECT * FROM EMPLOYEES

SELECT FIRST_NAME,
		LAST_NAME,
		MANAGER_ID,
	CASE
			WHEN MANAGER_ID = 100 THEN 'SUP. JUAN'
			WHEN MANAGER_ID = 101 THEN 'SUP. JOSE'
			WHEN MANAGER_ID = 102 THEN 'SUP. PEDRO SANTANA'
			WHEN MANAGER_ID = 103 THEN 'SUP.KATHERINE'

		ELSE 'NO HAY NINGUN AGENTE BAJO SUPERVISION'
	END AS 'SUPERVISORES ASIGNADOS A EMPLEADOS'

FROM EMPLOYEES
ORDER BY MANAGER_ID ASC;

----COMBINANDO CASES CON JOIN

SELECT	E.FIRST_NAME, 
		E.LAST_NAME,
		DE.DEPARTMENT_NAME, 
		E.SALARY,
	CASE 
		WHEN SALARY BETWEEN 00000 AND 10000 THEN 'SALARIO BAJO'
		WHEN SALARY BETWEEN 10001 AND 20000 THEN 'SALARIO INTERMEDIO'
		WHEN SALARY BETWEEN 20001 AND 30000 THEN 'SALARIO ALTO'
	ELSE 'SALARIO NO CLASIFICADO'
END AS 'CLASIFICACION DE SALARIO'
FROM EMPLOYEES E
JOIN DEPARTMENT DE ON E.DEPARTMENT_ID = DE.DEPARTMENT_ID
ORDER BY SALARY ASC, DEPARTMENT_NAME DESC;

