--1.WHERE
SELECT E.FIRST_NAME, 
		E.LAST_NAME,
		E.EMAIL,
		E.HIRE_DATE,
		CO.COUNTRY_NAME
FROM EMPLOYEES E
JOIN DEPARTMENT DE ON E.DEPARTMENT_ID = DE.DEPARTMENT_ID
JOIN LOCATIONS LO ON DE.LOCATION_ID = LO.LOCATION_ID
JOIN COUNTRY CO ON LO.COUNTRY_ID  = CO.COUNTRY_ID
JOIN REGION RE ON CO.REGION_ID = RE.REGION_ID
WHERE COUNTRY_NAME = 'CANADA';


---MODIFICANDO EL NOMBRE DE LA COLUMNA LIOCATON_ID POR LOCATION_ID
EXEC sp_rename 'DEPARTMENT.LIOCATION_ID', 'LOCATION_ID', 'COLUMN';

--2.GROUP BY (SE AGRUPA POR LAS COLUMNAS QUE NO TIENEN FUNCION AGREGADAS COMO: COUNT, SUM, MIN, AVG)
SELECT COUNT (DISTINCT FIRST_NAME) AS 'CANTIDAD DE NOMBRES', LAST_NAME, PHONE_NUMBER, SUM(SALARY) AS 'SUMA DE SALARIO'
FROM EMPLOYEES
GROUP BY FIRST_NAME, LAST_NAME, PHONE_NUMBER

--2.GROUP BY CON JOIN ADICIONADO

SELECT E.FIRST_NAME, 
		E.LAST_NAME,
		CO.COUNTRY_NAME,
		SUM(SALARY)AS 'SUMA SALARIO'
FROM EMPLOYEES E
JOIN DEPARTMENT DE ON E.DEPARTMENT_ID = DE.DEPARTMENT_ID
JOIN LOCATIONS LO ON DE.LOCATION_ID = LO.LOCATION_ID
JOIN COUNTRY CO ON LO.COUNTRY_ID  = CO.COUNTRY_ID
JOIN REGION RE ON CO.REGION_ID = RE.REGION_ID
WHERE COUNTRY_NAME = 'CANADA'
GROUP BY FIRST_NAME, LAST_NAME, COUNTRY_NAME;

--3.JOIN (NOS PERMITE ENLAZAR VARIAS TABLAS PARA PODER OBTENER REGISTROS)

SELECT	E.FIRST_NAME, 
		E.LAST_NAME,
		E.JOB_ID,
		L.CITY,
		L.STATE_PROVINCE
FROM EMPLOYEES E
		JOIN DEPARTMENT DE ON E.DEPARTMENT_ID = DE.DEPARTMENT_ID
		JOIN LOCATIONS L ON DE.LOCATION_ID = L.LOCATION_ID
WHERE CITY = 'SEATTLE' AND JOB_ID = 5;		
		
--4.HAVING ()
SELECT FIRST_NAME, LAST_NAME, PHONE_NUMBER, AVG(SALARY) AS 'AVERAGE DE SALARIO', COUNT(DEPARTMENT_ID) AS 'CONTEO DE DEPARTAMENTO'
FROM EMPLOYEES
WHERE LAST_NAME = 'lorentz'
GROUP BY FIRST_NAME, LAST_NAME, PHONE_NUMBER
HAVING AVG(SALARY) > 5000;

---REALIZANDO OTRO HAVING

SELECT	E.LAST_NAME AS APELLIDO, 
		E.HIRE_DATE AS FECHA_CONTRATACION, 
		E.MANAGER_ID AS ID_SUPERVISOR,
		MIN(SALARY) AS SALARIO_MINIMO,
		JH.START_DATE AS FECHA_INICIO
FROM EMPLOYEES E
JOIN JOB_HISTORY JH ON JH.EMPLOYEE_ID = E.EMPLOYEE_ID
WHERE LAST_NAME = UPPER('KOCHAR')
GROUP BY E.LAST_NAME, E.HIRE_DATE, E.MANAGER_ID, JH.START_DATE
HAVING MIN(SALARY) =8163;


